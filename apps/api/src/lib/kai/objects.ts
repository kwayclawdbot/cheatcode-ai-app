/**
 * Kai object envelopes: build, persist, and derive.
 *
 * Envelope shape is 02 §7: {id, type, created_at, model, prompt_version,
 * disclosures[], refs, payload}.
 */
import {
  KaiObjectEnvelope,
  type GradedSetupPayload,
  type KaiObjectType,
  type ExplainLevels,
} from '@shared/api';
import { serviceClient } from '../db';
import { log } from '../log';
import { KAI_MODEL, KAI_PROMPT_VERSION } from '../env';
import { quoteFromSnapshot } from '../market';
import { entryPrice, invalidationPrice, normalizeTargets, type SetupRow } from './context';

/** Objects derived from database rows rather than generated by the model. */
export const DETERMINISTIC_MODEL = 'deterministic/v1';

export const DISCLOSURES = {
  paperOnly: 'paper_only',
  education: 'education_not_advice',
} as const;

export function envelope(opts: {
  id: string;
  type: KaiObjectType;
  payload: unknown;
  model?: string;
  createdAt?: string;
  refs?: Record<string, unknown> | null;
  disclosures?: string[];
}): KaiObjectEnvelope {
  return KaiObjectEnvelope.parse({
    id: opts.id,
    type: opts.type,
    created_at: opts.createdAt ?? new Date().toISOString(),
    model: opts.model ?? KAI_MODEL(),
    prompt_version: KAI_PROMPT_VERSION,
    disclosures: opts.disclosures ?? [DISCLOSURES.paperOnly, DISCLOSURES.education],
    refs: opts.refs ?? null,
    payload: opts.payload,
  });
}

/** Persist a generated object to `kai_objects` and return its envelope. */
export async function persistKaiObject(opts: {
  type: KaiObjectType;
  payload: unknown;
  userId: string | null;
  refs?: Record<string, unknown> | null;
  model?: string;
  disclosures?: string[];
  requestId?: string;
}): Promise<KaiObjectEnvelope | null> {
  try {
    const db = serviceClient();
    const { data, error } = await db
      .from('kai_objects')
      .insert({
        type: opts.type,
        payload: opts.payload as never,
        disclosures: opts.disclosures ?? [DISCLOSURES.paperOnly, DISCLOSURES.education],
        model: opts.model ?? KAI_MODEL(),
        prompt_version: KAI_PROMPT_VERSION,
        refs: (opts.refs ?? null) as never,
        user_id: opts.userId,
      })
      .select('id,type,payload,disclosures,model,prompt_version,refs,created_at')
      .single();
    if (error || !data) {
      log('error', opts.requestId ?? '-', 'kai_object.persist_failed', {
        type: opts.type,
        message: error?.message,
      });
      return null;
    }
    const row = data as unknown as {
      id: string;
      type: KaiObjectType;
      payload: unknown;
      disclosures: string[];
      model: string;
      prompt_version: string;
      refs: Record<string, unknown> | null;
      created_at: string;
    };
    return envelope({
      id: row.id,
      type: row.type,
      payload: row.payload,
      model: row.model,
      createdAt: row.created_at,
      refs: row.refs,
      disclosures: row.disclosures,
    });
  } catch (e) {
    log('error', opts.requestId ?? '-', 'kai_object.persist_threw', {
      type: opts.type,
      message: e instanceof Error ? e.message : String(e),
    });
    return null;
  }
}

/** Look up a cached object by exact refs match (used for the daily briefing). */
export async function findCachedObject(
  type: KaiObjectType,
  refs: Record<string, unknown>
): Promise<KaiObjectEnvelope | null> {
  const db = serviceClient();
  const { data, error } = await db
    .from('kai_objects')
    .select('id,type,payload,disclosures,model,prompt_version,refs,created_at')
    .eq('type', type)
    .contains('refs', refs as never)
    .order('created_at', { ascending: false })
    .limit(1);
  if (error || !data || data.length === 0) return null;
  const row = data[0] as unknown as {
    id: string;
    type: KaiObjectType;
    payload: unknown;
    disclosures: string[];
    model: string;
    refs: Record<string, unknown> | null;
    created_at: string;
  };
  return envelope({
    id: row.id,
    type: row.type,
    payload: row.payload,
    model: row.model,
    createdAt: row.created_at,
    refs: row.refs,
    disclosures: row.disclosures,
  });
}

